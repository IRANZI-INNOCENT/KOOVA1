from django.db import models


class MorningBrief(models.Model):
    """
    A daily business brief generated by Kova.

    Each brief is tied to a business and a calendar date. The sections
    JSON stores the structured 6-part brief (pulse, pending,
    opportunities, performance, plan, kova_actions). The evidence JSON
    stores the raw data snapshot that informed the brief so we can
    always trace recommendations back to facts.
    """

    class Status(models.TextChoices):
        GENERATING = "generating", "Generating"
        READY = "ready", "Ready"
        FAILED = "failed", "Failed"

    business = models.ForeignKey(
        "businesses.Business",
        on_delete=models.CASCADE,
        related_name="morning_briefs",
    )

    date = models.DateField(
        help_text="The calendar date this brief covers.",
    )

    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.GENERATING,
    )

    greeting = models.CharField(
        max_length=200,
        blank=True,
        help_text="Personalised greeting line.",
    )

    # Structured brief sections
    sections = models.JSONField(
        default=dict,
        blank=True,
        help_text="The 6-part brief: pulse, pending, opportunities, performance, plan, kova_actions.",
    )

    # Raw evidence snapshot used to generate the brief
    evidence = models.JSONField(
        default=dict,
        blank=True,
        help_text="Data snapshot: social stats, content counts, leads, commerce, actions.",
    )

    error_message = models.TextField(
        blank=True,
        help_text="If status is failed, the reason.",
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-date", "-created_at"]
        unique_together = [("business", "date")]

    def __str__(self):
        return f"{self.business.name} brief {self.date}"

from rest_framework import serializers

from .models import Business


class BusinessSerializer(serializers.ModelSerializer):
    """
    Serialize business information for the Kova API.

    The business owner is intentionally excluded from the writable
    request fields. Ownership is assigned from request.user in the
    API view so clients cannot assign businesses to arbitrary users.
    """

    class Meta:
        model = Business
        fields = [
            "id",
            "name",
            "description",
            "industry",
            "location",
            "email",
            "phone",
            "created_at",
            "updated_at",
        ]

        # These fields are generated by the server and should never
        # be supplied by the client when creating a business.
        read_only_fields = [
            "id",
            "created_at",
            "updated_at",
        ]
"""
Kova Content models.

Kova acts as a social media manager.  When the owner says "promote this
product" or "announce this sale," Kova generates adapted content for
every connected channel simultaneously — Instagram carousel, Facebook
post, reel script, story, and so on — all from a single content brief.

A ContentBatch groups the pieces that were generated together.
Each Content record is one platform-specific, format-specific asset
inside that batch.

Commerce integration:
- A Content can reference a Product.  Product images, prices, selling
  points, and descriptions feed directly into content creation.
- media_urls stores selected product images (or future uploads).
- slides stores per-slide data for carousel content.
- hashtags stores AI-suggested or owner-chosen hashtags.
"""

from __future__ import annotations

import uuid

from django.db import models

from apps.businesses.models import Business


class ContentBatch(models.Model):
    """
    A group of Content records generated from one brief.

    When the owner asks Kova to create content, Kova generates adapted
    pieces for every connected channel.  The batch ties them together
    so they can be reviewed, approved, and published as a unit.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    business = models.ForeignKey(
        Business,
        on_delete=models.CASCADE,
        related_name="content_batches",
    )

    product = models.ForeignKey(
        "commerce.Product",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="content_batches",
    )

    brief = models.TextField(
        blank=True,
        help_text="What the owner asked Kova to create.",
    )

    class Kind(models.TextChoices):
        PRODUCT = "product", "Product campaign"
        ORGANIC = "organic", "Organic campaign"
        OWNER_VIDEO = "owner_video", "Owner video"

    kind = models.CharField(
        max_length=20,
        choices=Kind.choices,
        default=Kind.PRODUCT,
    )

    organic_theme = models.CharField(
        max_length=40,
        blank=True,
        help_text="Theme key when kind is organic (educate, tip, etc.).",
    )

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"Batch {self.id} — {self.business.name}"


class Content(models.Model):
    """
    A social media content asset managed by Kova.

    Content is generated by the Brain for a specific connected channel
    and content format.  The owner reviews and edits before approving.
    """

    class Status(models.TextChoices):
        DRAFT = "draft", "Draft"
        APPROVED = "approved", "Approved"
        PUBLISHED = "published", "Published"
        REJECTED = "rejected", "Rejected"

    class Platform(models.TextChoices):
        INSTAGRAM = "instagram", "Instagram"
        FACEBOOK = "facebook", "Facebook"
        TIKTOK = "tiktok", "TikTok"
        WHATSAPP = "whatsapp", "WhatsApp"
        X = "x", "X"
        OTHER = "other", "Other"

    class ContentType(models.TextChoices):
        POST = "post", "Post"
        REEL = "reel", "Reel"
        STORY = "story", "Story"
        CAROUSEL = "carousel", "Carousel"
        STATUS = "status", "Status"
        OTHER = "other", "Other"

    business = models.ForeignKey(
        Business,
        on_delete=models.CASCADE,
        related_name="contents",
    )

    batch = models.ForeignKey(
        ContentBatch,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="contents",
        help_text="The batch this content was generated with.",
    )

    product = models.ForeignKey(
        "commerce.Product",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="contents",
        help_text="The product this content is about (if any).",
    )

    social_account = models.ForeignKey(
        "social.SocialAccount",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="contents",
        help_text="The connected channel this content is for.",
    )

    platform = models.CharField(
        max_length=30,
        choices=Platform.choices,
    )

    content_type = models.CharField(
        max_length=30,
        choices=ContentType.choices,
    )

    caption = models.TextField()

    call_to_action = models.CharField(
        max_length=500,
        blank=True,
    )

    hashtags = models.JSONField(
        default=list,
        blank=True,
        help_text="List of hashtag strings (without #).",
    )

    media_urls = models.JSONField(
        default=list,
        blank=True,
        help_text="Ordered list of image/video URLs for the post.",
    )

    slides = models.JSONField(
        default=list,
        blank=True,
        help_text=(
            "Carousel slides. Each item: "
            '{"caption": "...", "media_url": "...", "product_id": N | null}.'
        ),
    )

    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.DRAFT,
    )

    created_by_ai = models.BooleanField(
        default=True,
    )

    published_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.platform} {self.content_type} — {self.business.name}"


class OwnerMediaAsset(models.Model):
    """Owner-uploaded image or short video for social publishing."""

    class MediaType(models.TextChoices):
        IMAGE = "image", "Image"
        VIDEO = "video", "Video"

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)

    business = models.ForeignKey(
        Business,
        on_delete=models.CASCADE,
        related_name="owner_media",
    )

    media_type = models.CharField(
        max_length=10,
        choices=MediaType.choices,
    )

    file = models.FileField(upload_to="content/owner_media/")

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.media_type} — {self.business.name}"
